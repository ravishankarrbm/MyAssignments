//Number – a whole number or decimal value
var rollNumber=12;
console.log(rollNumber);
console.log(typeof rollNumber);

//String – text written using quotes or backticks
var friendName="Ravi";
console.log(friendName);
console.log(typeof friendName);

//Boolean – a value of true or false
var isPassed=false;
console.log(isPassed);
console.log(typeof isPassed);

//BigInt – a large integer written with the n suffix
var num1=51606515516515n;
console.log(num1);
console.log(typeof num1);

var num2=999999994551515151559999;
console.log(num2);

//Undefined – a declared variable with no assigned value
var check;
console.log(check);

//Null – an intentional absence of a value
var middleName=null;
console.log(middleName);